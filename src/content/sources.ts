// Every URL below was requested on the access date. "resolved" means the URL returned HTTP 200
// (after redirects) to an automated request and, for framework and guidance documents, the page
// was read to confirm its title, version and date. "blocked-automated-check" means the host
// refused the automated request (HTTP 403), so the link is listed but not confirmed by this review.
// Research entries are arXiv records: the title and first-posted date were confirmed through the
// arXiv API; a later peer-reviewed venue is not asserted here.

const ACCESSED = '2026-10-20';

const ARXIV_NOTE =
  'arXiv record. Title and first-posted date confirmed via the arXiv API; later peer-reviewed publication, if any, not asserted here. Empirical results apply to the threat model and systems the authors tested.';

function arxiv(id: string, title: string, posted: string, publisher: string): Source {
  return {
    id: `arxiv-${id}`,
    title,
    publisher,
    url: `https://arxiv.org/abs/${id}`,
    kind: 'research',
    version: `arXiv:${id}`,
    published: posted,
    accessed: ACCESSED,
    linkCheck: 'resolved',
    note: ARXIV_NOTE,
  };
}

